//! Section tracking, default speech ids, and collision checks shared by parse and filmScript.

import { CODE_OPEN, codeClose } from "./grammar.js";
import type { ScriptItem } from "./types.js";

const TITLE = /^ {0,3}#[ \t]+(.*?)(?:[ \t]+#+)?[ \t]*$/;
const HEADING = /^ {0,3}#{1,6}[ \t]+(.*?)(?:[ \t]+#+)?[ \t]*$/;

/** The last heading in a run of Markdown, ignoring fenced code. */
export function lastHeading(text: string): string | null {
  const lines = text.split("\n");
  let heading: string | null = null;
  for (let i = 0; i < lines.length; i++) {
    const code = CODE_OPEN.exec(lines[i]!);
    if (code) {
      const close = codeClose(code[1]!);
      i++;
      while (i < lines.length && !close.test(lines[i]!)) i++;
      continue;
    }
    const match = HEADING.exec(lines[i]!);
    if (match && match[1]) heading = match[1];
  }
  return heading;
}

/** The first level-1 heading in the document's Markdown, ignoring fenced code. */
export function firstTitle(items: readonly ScriptItem[]): string | null {
  for (const item of items) {
    if (item.kind !== "markdown") continue;
    const lines = item.text.split("\n");
    for (let i = 0; i < lines.length; i++) {
      const code = CODE_OPEN.exec(lines[i]!);
      if (code) {
        const close = codeClose(code[1]!);
        i++;
        while (i < lines.length && !close.test(lines[i]!)) i++;
        continue;
      }
      const match = TITLE.exec(lines[i]!);
      if (match && match[1]) return match[1];
    }
  }
  return null;
}

export function slugifySection(section: string | null): string {
  if (!section) return "speech";
  const slug = section
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return slug || "speech";
}

function makeDefaultId(prefix: string, index: number): string {
  const suffix = `-${index}`;
  const maxPrefix = 80 - suffix.length;
  const trimmed =
    prefix.length > maxPrefix ? prefix.slice(0, maxPrefix).replace(/-+$/, "") || "speech" : prefix;
  return `${trimmed}${suffix}`;
}

export interface ResolvedBlockMeta {
  section: string | null;
  id: string | null;
  /** True when `id` was generated by speech default rather than written explicitly. */
  defaulted: boolean;
}

/**
 * Resolve every block's section and effective id (applying `<shotId>-<n>` or
 * `<section-slug>-<n>` defaults to speech blocks without `id=`), then detect
 * any collisions across explicit and defaulted ids.
 */
export function resolveBlocks(items: readonly ScriptItem[]): {
  meta: ResolvedBlockMeta[];
  collisions: Map<number, string>;
} {
  const meta: ResolvedBlockMeta[] = [];
  let section: string | null = null;
  let currentShotId: string | null = null;
  let shotSpeechCount = 0;
  let sectionSpeechCount = 0;

  for (const item of items) {
    if (item.kind === "markdown") {
      const heading = lastHeading(item.text);
      if (heading !== null) {
        section = heading;
        sectionSpeechCount = 0;
      }
      continue;
    }
    if (item.kind === "shot") {
      currentShotId = item.id ?? null;
      shotSpeechCount = 0;
      meta.push({ section, id: item.id ?? null, defaulted: false });
      continue;
    }
    if (item.kind === "card") {
      meta.push({ section, id: item.id ?? null, defaulted: false });
      continue;
    }
    // speech
    let fallback: string;
    if (currentShotId !== null) {
      shotSpeechCount++;
      fallback = makeDefaultId(currentShotId, shotSpeechCount);
    } else {
      sectionSpeechCount++;
      fallback = makeDefaultId(slugifySection(section), sectionSpeechCount);
    }
    if (item.id !== undefined) {
      meta.push({ section, id: item.id, defaulted: false });
    } else if (item.rawId !== undefined) {
      meta.push({ section, id: null, defaulted: false });
    } else {
      meta.push({ section, id: fallback, defaulted: true });
    }
  }

  const counts = new Map<string, number>();
  for (const entry of meta) {
    if (entry.id) counts.set(entry.id, (counts.get(entry.id) ?? 0) + 1);
  }

  const collisions = new Map<number, string>();
  meta.forEach((entry, index) => {
    if (!entry.id || (counts.get(entry.id) ?? 0) < 2) return;
    collisions.set(index, entry.id);
    entry.id = null;
  });

  return { meta, collisions };
}
