#!/usr/bin/env node
/**
 * Build browser virtual-module sources from real packages.
 *
 * Writes gitignored src/bundler/browser-virtuals.gen.ts — never hand-edit.
 * Source of truth: template-runtime.ts, @superimg/types define, stdlib dist.
 *
 * Run: node scripts/build-browser-virtuals.mjs
 */

import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { rolldown } from "rolldown";

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(__dirname, "..");
const srcDir = join(pkgRoot, "src");
const outPath = join(srcDir, "bundler", "browser-virtuals.gen.ts");
const hashPath = join(pkgRoot, "dist", "browser-virtuals.source-hash");

const stdlibDist = join(pkgRoot, "..", "superimg-stdlib", "dist");
const typesEntry = join(pkgRoot, "..", "superimg-types", "dist", "index.js");
const runtimeEntry = join(srcDir, "template-runtime.ts");

function requireFile(path, label) {
  if (!existsSync(path)) {
    throw new Error(
      `build-browser-virtuals: missing ${label} at ${path}. Build dependencies first.`,
    );
  }
}

function gatherFiles(dir, exts = [".ts", ".js"]) {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) {
      if (name === "generated" || name === "__tests__") continue;
      out.push(...gatherFiles(full, exts));
    } else if (exts.some((e) => name.endsWith(e)) && !name.endsWith(".gen.ts")) {
      out.push(full);
    }
  }
  return out;
}

/** Hash of inputs that affect browser virtual content (not the bundle itself). */
export function computeSourceHash() {
  const files = [
    runtimeEntry,
    typesEntry,
    join(stdlibDist, "code.js"),
    join(stdlibDist, "cue", "index.js"),
    join(stdlibDist, "text.js"),
    join(__dirname, "build-browser-virtuals.mjs"),
    ...gatherFiles(join(srcDir, "composition")),
    ...gatherFiles(join(srcDir, "shared")),
  ].filter((f) => existsSync(f));

  files.sort();
  const h = createHash("sha256");
  for (const file of files) {
    const rel = relative(pkgRoot, file);
    h.update(`${rel}\n`);
    h.update(readFileSync(file, "utf8"));
    h.update("\n");
  }
  return h.digest("hex").slice(0, 16);
}

async function bundleEntry(input, label) {
  const bundle = await rolldown({
    input,
    external: [],
  });
  try {
    const { output } = await bundle.generate({ format: "es" });
    const code = output[0]?.code;
    if (!code) throw new Error(`build-browser-virtuals: empty bundle for ${label}`);
    return code;
  } finally {
    await bundle.close();
  }
}

async function bundleDefineOnly() {
  const virtualId = resolve(srcDir, "define-entry.ts");
  const defineSource = `
export { define, defineConfig, defineBatch } from ${JSON.stringify(typesEntry)};
`;
  const bundle = await rolldown({
    input: virtualId,
    external: [],
    plugins: [
      {
        name: "define-entry",
        resolveId(id) {
          return id === virtualId ? id : null;
        },
        load(id) {
          return id === virtualId ? defineSource : null;
        },
      },
    ],
  });
  try {
    const { output } = await bundle.generate({ format: "es" });
    const code = output[0]?.code;
    if (!code) throw new Error("build-browser-virtuals: empty define bundle");
    return code;
  } finally {
    await bundle.close();
  }
}

async function main() {
  requireFile(runtimeEntry, "template-runtime.ts");
  requireFile(typesEntry, "@superimg/types dist");
  requireFile(join(stdlibDist, "code.js"), "stdlib code.js");
  requireFile(join(stdlibDist, "cue", "index.js"), "stdlib cue");
  requireFile(join(stdlibDist, "text.js"), "stdlib text.js");

  console.log("Building browser virtual modules from real sources...");

  const sourceHash = computeSourceHash();

  const [runtimeCode, defineCode] = await Promise.all([
    bundleEntry(runtimeEntry, "template-runtime"),
    bundleDefineOnly(),
  ]);

  const modules = {
    "\0superimg-virtual": runtimeCode,
    "\0superimg-define": defineCode,
    "\0stdlib-code": readFileSync(join(stdlibDist, "code.js"), "utf8"),
    "\0stdlib-cue": readFileSync(join(stdlibDist, "cue", "index.js"), "utf8"),
    "\0stdlib-text": readFileSync(join(stdlibDist, "text.js"), "utf8"),
    "\0stdlib-noop": "export {}",
  };

  const body = `// AUTO-GENERATED by scripts/build-browser-virtuals.mjs — do not edit
// source-hash: ${sourceHash}
// Regenerate: pnpm run build (or node scripts/build-browser-virtuals.mjs)

export const BROWSER_VIRTUALS_SOURCE_HASH = ${JSON.stringify(sourceHash)};

export const BROWSER_VIRTUAL_MODULES: Record<string, string> = ${JSON.stringify(modules, null, 2)};
`;

  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, body);

  mkdirSync(dirname(hashPath), { recursive: true });
  writeFileSync(hashPath, sourceHash + "\n");

  console.log(`Wrote ${outPath}`);
  console.log(`  superimg-virtual: ${runtimeCode.length} bytes`);
  console.log(`  superimg-define:  ${defineCode.length} bytes`);
  console.log(`  source-hash: ${sourceHash}`);
}

const isMain =
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
