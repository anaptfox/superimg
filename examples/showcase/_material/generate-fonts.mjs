import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const fonts = [];
for (const weight of [400, 500, 700]) {
  const bytes = await readFile(new URL(`../../../packages/superimg-core/assets/fonts/Inter-${weight}.ttf`, import.meta.url));
  fonts.push({ weight, base64: bytes.toString('base64'), sha256: createHash('sha256').update(bytes).digest('hex') });
}
const target = new URL('./font-data.ts', import.meta.url);
await writeFile(target, `// Generated by generate-fonts.mjs from the repository's bundled Inter fonts.\nexport const FONT_DATA = ${JSON.stringify(fonts)} as const;\n`);
process.stdout.write(`Wrote portable Inter font bytes: ${fileURLToPath(target)}\n`);
